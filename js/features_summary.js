  function showToast(msg) {
    const existing = document.getElementById("pwa-toast");
    if (existing) existing.remove();
    const toast = document.createElement("div");
    toast.id = "pwa-toast";
    toast.className = "pwa-toast show";
    toast.textContent = msg;
    document.body.appendChild(toast);
    setTimeout(() => {
      toast.classList.remove("show");
      setTimeout(() => toast.remove(), 300);
    }, 3000);
  }

  function copyFeaturesList() {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(FEATURES_TEXT).then(() => {
        showToast("മുഴുവൻ ഫീച്ചർ ലിസ്റ്റും കോപ്പി ചെയ്തു! ✅");
      }).catch(() => {
        fallbackCopy();
      });
    } else {
      fallbackCopy();
    }
  }

  function fallbackCopy() {
    const ta = document.createElement("textarea");
    ta.value = FEATURES_TEXT;
    ta.style.position = "fixed";
    ta.style.opacity = "0";
    document.body.appendChild(ta);
    ta.select();
    try {
      document.execCommand("copy");
      showToast("മുഴുവൻ ഫീച്ചർ ലിസ്റ്റും കോപ്പി ചെയ്തു! ✅");
    } catch (e) {
      showToast("കോപ്പി ചെയ്യാൻ കഴിഞ്ഞില്ല");
    }
    document.body.removeChild(ta);
  }

  function initFeaturesSummary() {
    // 1. WhatsApp share buttons prefill
    const waUrl = `https://api.whatsapp.com/send?text=${encodeURIComponent(FEATURES_TEXT)}`;
    const waTop = document.getElementById("share-features-wa-btn");
    const waBottom = document.getElementById("share-features-wa-btn-bottom");
    if (waTop) waTop.href = waUrl;
    if (waBottom) waBottom.href = waUrl;

    // 2. Copy buttons
    const copyTop = document.getElementById("copy-features-list-btn");
    const copyBottom = document.getElementById("copy-features-list-btn-bottom");
    if (copyTop) copyTop.addEventListener("click", copyFeaturesList);
    if (copyBottom) copyBottom.addEventListener("click", copyFeaturesList);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", initFeaturesSummary);
  } else {
    initFeaturesSummary();
  }
